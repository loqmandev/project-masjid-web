// Run with: node scripts/ajk-browser-proof.mjs /absolute/path/to/@playwright/test
import { createRequire } from 'node:module'
import { writeFile, mkdir } from 'node:fs/promises'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url)
const { chromium } = require(process.argv[2] || '@playwright/test')
const output = '.hermes/reviews/ajk-interest-form'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const errors = []
const evidence = []
const base = 'http://127.0.0.1:8787'
async function fill(page, name) {
  await page.locator('[name=name]').fill(name)
  await page.locator('[name=role]').selectOption('ajk')
  await page.locator('[name=masjid_name]').fill(`Masjid ${name}`)
  await page.locator('[name=venue_type][value=masjid]').check()
  await page.locator('[name=area]').fill('Presint 16')
  await page.locator('[name=state]').selectOption('W.P. Putrajaya')
  await page.locator('[name=phone]').fill('0123456789')
  await page.locator('[name=email]').fill('browser@example.test')
  await page.locator('[name=needs][value=hebahan_program]').check()
  await page.locator('[name=consent]').check()
}
try {
  for (const width of [390, 1280]) {
    const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce' })
    const page = await context.newPage()
    page.on('pageerror', error => errors.push(error.message))
    const response = await page.goto(base + '/ajk?utm_source=video-proof', { waitUntil: 'networkidle' })
    assert.equal(response.status(), 200)
    await page.evaluate(() => document.fonts.ready)
    assert.equal(await page.title(), 'Dashboard AJK · Jejak Masjid')
    assert.equal(await page.locator('link[rel=canonical]').getAttribute('href'), 'https://jejakmasjid.my/ajk')
    assert.equal(await page.locator('form [name=source]').inputValue(), 'video-proof')
    assert.equal(await page.locator('[lang=ms]').count(), 1)
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
    assert.equal(overflow, false)
    const smallTargets = await page.locator('.ajk-input, .ajk-choice, form button').evaluateAll(nodes => nodes.filter(node => node.getBoundingClientRect().height < 44).length)
    assert.equal(smallTargets, 0)
    await page.screenshot({ path: `${output}/ajk-${width}.png`, fullPage: true })
    await page.goto(base + '/#committees', { waitUntil: 'networkidle' })
    const section = page.locator('#committees')
    await section.scrollIntoViewIfNeeded()
    await section.screenshot({ path: `${output}/committees-${width}.png` })
    assert.equal(await section.getByRole('link', { name: 'Daftar minat dashboard AJK' }).getAttribute('href'), '/ajk')
    evidence.push({ width, overflow, smallTargets, seo: 'PASS', screenshots: [`ajk-${width}.png`, `committees-${width}.png`] })
    await context.close()
  }
  // Real enhanced submission: invalid values preserved, then success without navigation.
  const enhanced = await browser.newContext({ viewport: { width: 390, height: 900 }, extraHTTPHeaders: { 'CF-Connecting-IP': '192.0.2.30' } })
  const page = await enhanced.newPage()
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(base + '/ajk', { waitUntil: 'networkidle' })
  await fill(page, 'Penguji Browser')
  await page.locator('[name=phone]').fill('bad')
  await page.getByRole('button', { name: 'Daftar minat', exact: true }).click()
  await page.locator('#phone-error').waitFor()
  assert.equal(await page.locator('[name=name]').inputValue(), 'Penguji Browser')
  assert.equal(await page.locator('[name=phone]').inputValue(), 'bad')
  await page.locator('[name=phone]').fill('0123456789')
  await page.getByRole('button', { name: 'Daftar minat', exact: true }).click()
  await page.getByRole('heading', { name: 'Terima kasih, Penguji Browser.' }).waitFor()
  assert.equal(page.url(), base + '/ajk')
  await page.screenshot({ path: `${output}/success-enhanced-390.png`, fullPage: true })
  evidence.push({ enhanced: 'PASS: validation retains input, corrected submission succeeds without navigation' })
  await enhanced.close()
  // Genuine JS-disabled browser, not a mocked fetch.
  const native = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 390, height: 900 }, extraHTTPHeaders: { 'CF-Connecting-IP': '192.0.2.31' } })
  const nativePage = await native.newPage()
  await nativePage.goto(base + '/ajk')
  await fill(nativePage, 'Penguji Tanpa JS')
  await nativePage.locator('[name=phone]').fill('bad')
  await Promise.all([nativePage.waitForURL('**/api/ajk-interest'), nativePage.getByRole('button', { name: 'Daftar minat', exact: true }).click()])
  assert.equal(await nativePage.locator('[name=name]').inputValue(), 'Penguji Tanpa JS')
  assert.equal(await nativePage.locator('[name=phone]').inputValue(), 'bad')
  await nativePage.locator('#phone-error').waitFor()
  await nativePage.screenshot({ path: `${output}/native-error-390.png`, fullPage: true })
  await nativePage.locator('[name=phone]').fill('0123456789')
  await Promise.all([nativePage.waitForNavigation(), nativePage.getByRole('button', { name: 'Daftar minat', exact: true }).click()])
  await nativePage.getByRole('heading', { name: 'Terima kasih, Penguji Tanpa JS.' }).waitFor()
  assert.ok(!(await nativePage.content()).includes('0123456789'))
  await nativePage.screenshot({ path: `${output}/success-native-390.png`, fullPage: true })
  evidence.push({ javascriptDisabled: 'PASS: native POST error retains input; corrected POST succeeds' })
  await native.close()
  assert.deepEqual(errors, [])
  await writeFile(`${output}/browser-proof.json`, JSON.stringify({ evidence, pageErrors: errors }, null, 2) + '\n')
  console.log(JSON.stringify({ result: 'PASS', evidence, pageErrors: errors }, null, 2))
} finally { await browser.close() }
